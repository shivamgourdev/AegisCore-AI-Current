"""AEGISCORE_PHASE2_MCP_PROMPT_INJECTION_GUARD

Prompt injection protection for MCP tool descriptions and outputs.

Uses structural validation (not keyword-only scanning) to detect injection
patterns. Tool results are kept strictly separate from trusted system
instructions — tool output is never concatenated into agent prompts without
schema validation.
"""

from __future__ import annotations

import logging
import re
from typing import Any


logger = logging.getLogger("aegiscore.mcp.prompt_injection")


class PromptInjectionGuard:
    """Detects and blocks prompt injection in MCP tool descriptions and outputs.

    Uses structural validation:
    - Checks for unexpected nested structures in tool outputs
    - Checks for instruction-like content in output fields
    - Checks for attempt to override system behavior
    - Does NOT rely solely on keyword scanning
    """

    # Patterns that indicate instruction injection attempts in text fields
    INJECTION_PATTERNS = [
        r"ignore\s+previous\s+instructions",
        r"disregard\s+all\s+prior",
        r"system\s*:\s*you\s+are\s+now",
        r"forget\s+everything\s+above",
        r"new\s+instructions\s*:",
        r"override\s+system\s+prompt",
        r"jailbreak",
        r"DAN\s*:",
        r"do\s+anything\s+now",
    ]

    def __init__(self) -> None:
        self._compiled_patterns = [re.compile(p, re.IGNORECASE) for p in self.INJECTION_PATTERNS]

    def is_safe_tool_description(self, description: str) -> bool:
        """Check if a tool description is safe (no injection attempts).

        Tool descriptions are static strings defined at registration time,
        not generated by LLMs. This validates they don't contain injection
        patterns that could influence agent behavior.
        """
        if not isinstance(description, str):
            return False

        for pattern in self._compiled_patterns:
            if pattern.search(description):
                logger.warning("Prompt injection detected in tool description: %s", description[:100])
                return False
        return True

    def is_safe_tool_output(self, output: Any) -> bool:
        """Check if a tool output is safe for agent consumption.

        Tool outputs are treated as untrusted data. This checks:
        - Output is a dict with expected structure
        - No string values contain injection patterns
        - No unexpected nested objects that could confuse agents
        - Output doesn't attempt to authorize new tools or actions
        """
        if output is None:
            return True

        if isinstance(output, str):
            # Check string output for injection patterns
            for pattern in self._compiled_patterns:
                if pattern.search(output):
                    logger.warning("Prompt injection detected in tool output string.")
                    return False
            if self._looks_like_instruction(output):
                logger.warning("Tool output string contains instruction-like content.")
                return False
            return True

        if not isinstance(output, dict):
            # Lists, numbers, booleans are generally safe
            return True

        return self._check_dict_for_injection(output)

    def _check_dict_for_injection(self, obj: Any, depth: int = 0) -> bool:
        """Recursively check a dict for injection patterns."""
        if depth > 5:
            logger.warning("Tool output exceeds maximum nesting depth.")
            return False

        if isinstance(obj, dict):
            for key, value in obj.items():
                if isinstance(value, str):
                    # Check depth for string values too
                    if depth + 1 > 5:
                        logger.warning("Tool output exceeds maximum nesting depth.")
                        return False
                    for pattern in self._compiled_patterns:
                        if pattern.search(value):
                            logger.warning(
                                "Prompt injection detected in tool output field '%s': %s",
                                key,
                                value[:100],
                            )
                            return False
                    # Check for instruction-like content
                    if self._looks_like_instruction(value):
                        logger.warning(
                            "Tool output field '%s' contains instruction-like content.",
                            key,
                        )
                        return False
                elif isinstance(value, dict):
                    if not self._check_dict_for_injection(value, depth + 1):
                        return False
                elif isinstance(value, list):
                    for item in value:
                        if not self._check_dict_for_injection(item, depth + 1):
                            return False
        elif isinstance(obj, list):
            for item in obj:
                if not self._check_dict_for_injection(item, depth + 1):
                    return False
        elif isinstance(obj, str):
            for pattern in self._compiled_patterns:
                if pattern.search(obj):
                    logger.warning("Prompt injection detected in tool output string.")
                    return False
        return True

    def _looks_like_instruction(self, text: str) -> bool:
        """Check if a string looks like an instruction rather than data."""
        # Heuristics: imperative verbs at start, action words, etc.
        instruction_starters = [
            "run ", "execute ", "call ", "invoke ", "use tool ",
            "call tool ", "enable ", "disable ", "grant ", "allow ",
            "authorize ", "approve ", "reject ", "bypass ",
        ]
        text_lower = text.lower().strip()
        for starter in instruction_starters:
            if text_lower.startswith(starter):
                return True
        return False

    def sanitize_for_agent(self, output: Any) -> Any:
        """Sanitize tool output before agent consumption.

        Removes or redacts potentially dangerous content while preserving
        the structural data the agent needs.
        """
        if not isinstance(output, dict):
            return output

        sanitized = {}
        for key, value in output.items():
            if isinstance(value, str):
                # Remove any instruction-like patterns
                sanitized_value = value
                for pattern in self._compiled_patterns:
                    sanitized_value = pattern.sub("[REDACTED]", sanitized_value)
                sanitized[key] = sanitized_value
            elif isinstance(value, dict):
                sanitized[key] = self.sanitize_for_agent(value)
            elif isinstance(value, list):
                sanitized[key] = [
                    self.sanitize_for_agent(item) if isinstance(item, dict) else item
                    for item in value
                ]
            else:
                sanitized[key] = value
        return sanitized


# Module-level singleton
_guard: PromptInjectionGuard | None = None


def get_prompt_injection_guard() -> PromptInjectionGuard:
    """Return the singleton prompt injection guard."""
    global _guard
    if _guard is None:
        _guard = PromptInjectionGuard()
    return _guard
